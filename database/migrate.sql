-- ============================================================
-- 匿名聚合视图（学校端/社区端/树洞匿名流）
-- 说明：
--   * 视图为默认 security definer（所有者 postgres），底层表 RLS 不阻断聚合；
--   * 视图 WHERE 内嵌角色口径（current_uid_text() 定位当前用户）：
--     学校端只能取本校行，社区端只能取本区域行，未登录/无归属 → 0 行；
--   * 服务端 Node（service_role）不依赖本视图，用同样的口径做 JS 聚合
--     （见 server/routes/stats.js），两边结果口径一致；
--   * 视图不含任何学生个体字段（无 user_id/用户名/昵称），满足匿名统计要求。
-- ============================================================

-- ---------- 学校端：本校总览（学生数/测评数/AI 服务次数/风险事件数/测评均值） ----------
create or replace view public.school_cockpit as
select
  s.id                                       as school_id,
  s.school_name,
  s.region,
  count(distinct u.id)                       as student_count,
  count(distinct a.id)                       as assessment_count,
  count(distinct c.id)                       as ai_service_count,
  count(distinct c.id) filter (where c.risk_level in ('attention','high')) as risk_event_count,
  round(coalesce(avg(a.score), 0), 1)        as avg_assessment_score
from public.schools s
left join public.users u        on u.school_id = s.id and u.role = 'student'
left join public.assessments a  on a.user_id = u.id
left join public.chat_records c on c.user_id = u.id
where s.id::text = (
  select uu.school_id::text from public.users uu
  where uu.id::text = public.current_uid_text()
)
group by s.id, s.school_name, s.region;

-- ---------- 学校端：本校主要压力来源（测评类型 × 均值 × 次数） ----------
create or replace view public.school_pressure_sources as
select
  s.id as school_id,
  a.type,
  round(avg(a.score), 1) as avg_score,
  count(*) as count
from public.schools s
join public.users u        on u.school_id = s.id and u.role = 'student'
join public.assessments a  on a.user_id = u.id
where s.id::text = (
  select uu.school_id::text from public.users uu
  where uu.id::text = public.current_uid_text()
)
group by s.id, a.type;

-- ---------- 学校端：本校情绪分布 ----------
create or replace view public.school_emotion_distribution as
select
  s.id as school_id,
  e.emotion,
  count(*) as count
from public.schools s
join public.users u       on u.school_id = s.id and u.role = 'student'
join public.emotion_records e on e.user_id = u.id
where s.id::text = (
  select uu.school_id::text from public.users uu
  where uu.id::text = public.current_uid_text()
)
group by s.id, e.emotion;

-- ---------- 学校端：近 7 日 AI 服务趋势 ----------
create or replace view public.school_trend_7d as
select
  s.id as school_id,
  date_trunc('day', c.created_time)::date as day,
  count(*) as count
from public.schools s
join public.users u        on u.school_id = s.id and u.role = 'student'
join public.chat_records c on c.user_id = u.id
where c.created_time >= now() - interval '7 days'
  and s.id::text = (
    select uu.school_id::text from public.users uu
    where uu.id::text = public.current_uid_text()
  )
group by s.id, date_trunc('day', c.created_time)::date;

-- ---------- 社区端：区域总览（覆盖学校/服务人数/测评数/AI 服务次数） ----------
create or replace view public.community_overview as
select
  s.region,
  count(distinct s.id) as school_count,
  count(distinct u.id) as service_student_count,
  count(distinct a.id) as assessment_count,
  count(distinct c.id) as ai_service_count
from public.schools s
left join public.users u        on u.school_id = s.id and u.role = 'student'
left join public.assessments a  on a.user_id = u.id
left join public.chat_records c on c.user_id = u.id
where s.region = (
  select uu.region from public.users uu
  where uu.id::text = public.current_uid_text()
)
group by s.region;

-- ---------- 社区端：区域心理需求趋势（测评类型均值） ----------
create or replace view public.community_needs as
select
  s.region,
  a.type,
  round(avg(a.score), 1) as avg_score,
  count(*) as count
from public.schools s
join public.users u       on u.school_id = s.id and u.role = 'student'
join public.assessments a on a.user_id = u.id
where s.region = (
  select uu.region from public.users uu
  where uu.id::text = public.current_uid_text()
)
group by s.region, a.type;

-- ---------- 社区端：区域情绪分布 ----------
create or replace view public.community_emotion_distribution as
select
  s.region,
  e.emotion,
  count(*) as count
from public.schools s
join public.users u        on u.school_id = s.id and u.role = 'student'
join public.emotion_records e on e.user_id = u.id
where s.region = (
  select uu.region from public.users uu
  where uu.id::text = public.current_uid_text()
)
group by s.region, e.emotion;

-- ---------- 社区端：近 14 日服务趋势（测评/聊天/情绪三类事件） ----------
create or replace view public.community_trend_14d as
select
  s.region,
  date_trunc('day', x.created_time)::date as day,
  count(*) as count
from public.schools s
join public.users u on u.school_id = s.id and u.role = 'student'
join lateral (
  select a.created_time from public.assessments a where a.user_id = u.id
  union all
  select c.created_time from public.chat_records c where c.user_id = u.id
  union all
  select e.created_time from public.emotion_records e where e.user_id = u.id
) x on true
where x.created_time >= now() - interval '14 days'
  and s.region = (
    select uu.region from public.users uu
    where uu.id::text = public.current_uid_text()
  )
group by s.region, date_trunc('day', x.created_time)::date;

-- ---------- 树洞匿名公开流（不含 user_id，不暴露发布者） ----------
create or replace view public.tree_hole_feed as
select id, content, emotion, risk_level, created_time
from public.tree_hole;

