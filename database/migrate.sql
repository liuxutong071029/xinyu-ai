-- ============================================================
-- 1. schools 学校表（先建：users.school_id 外键依赖）
-- ============================================================
create table if not exists public.schools (
  id            bigint generated by default as identity primary key,
  school_name   text not null,
  region        text,
  student_count int  not null default 0,
  created_time  timestamptz not null default now(),
  constraint uq_schools_name_region unique (school_name, region)
);
create index if not exists idx_schools_region on public.schools(region);
comment on table public.schools is '学校表：学校端/社区端聚合统计的维度表';

-- ============================================================
-- 2. users 用户表
-- ============================================================
create table if not exists public.users (
  id           bigint generated by default as identity primary key,
  username     text not null unique,
  password     text not null,               -- sha256 十六进制哈希（演示级；生产建议接入 Supabase Auth）
  nickname     text not null,
  role         text not null check (role in ('student','parent','school','community')),
  age          int,
  gender       text,
  region       text,
  school_id    bigint references public.schools(id) on delete set null,
  avatar       text,
  created_time timestamptz not null default now()
);
create index if not exists idx_users_role   on public.users(role);
create index if not exists idx_users_school on public.users(school_id);
create index if not exists idx_users_region on public.users(region);
comment on table public.users is '用户表：四角色（学生 student / 家长 parent / 学校 school / 社区 community）';

-- ============================================================
-- 3. ai_personality AI 人格表
-- ============================================================
create table if not exists public.ai_personality (
  id               bigint generated by default as identity primary key,
  user_id          bigint not null references public.users(id) on delete cascade,
  personality_type text not null default '温柔倾听型'
                   check (personality_type in ('温柔倾听型','鼓励成长型','理性分析型')),
  created_time     timestamptz not null default now()
);
create index if not exists idx_ai_personality_user on public.ai_personality(user_id);
comment on table public.ai_personality is 'AI 伙伴人格配置（每位学生一条，可覆盖更新）';

-- ============================================================
-- 4. chat_records AI 聊天记录表
-- ============================================================
create table if not exists public.chat_records (
  id           bigint generated by default as identity primary key,
  user_id      bigint not null references public.users(id) on delete cascade,
  message      text not null,               -- 用户消息
  response     text not null,               -- AI 回复
  emotion      text,                        -- 情绪识别输出：压力/焦虑/开心/低落/平静
  risk_level   text not null default 'normal' check (risk_level in ('normal','attention','high')),
  created_time timestamptz not null default now()
);
create index if not exists idx_chat_user on public.chat_records(user_id);
create index if not exists idx_chat_risk on public.chat_records(risk_level);
comment on table public.chat_records is 'AI 聊天记录：家长/学校/社区端均不可见（RLS 无对应策略）';

-- ============================================================
-- 5. assessments 心理测评表
-- ============================================================
create table if not exists public.assessments (
  id           bigint generated by default as identity primary key,
  user_id      bigint not null references public.users(id) on delete cascade,
  type         text not null check (type in ('PHQ-9','GAD-7','压力测试','孤独感测试','睡眠测试')),
  score        int  not null,
  level        text,                        -- 分级结论，如 轻度/中度/正常
  result       text,                        -- 结果摘要
  created_time timestamptz not null default now()
);
create index if not exists idx_assessments_user on public.assessments(user_id);
comment on table public.assessments is '心理测评记录：家长可读已绑定孩子的测评摘要（趋势/AI 建议依据）';

-- ============================================================
-- 6. emotion_records 情绪记录表
-- ============================================================
create table if not exists public.emotion_records (
  id           bigint generated by default as identity primary key,
  user_id      bigint not null references public.users(id) on delete cascade,
  emotion      text not null check (emotion in ('开心','平静','焦虑','低落','疲惫')),
  pressure     text check (pressure in ('低','中','高')),
  source       text not null default '每日打卡' check (source in ('每日打卡','AI聊天','心理测评')),
  created_time timestamptz not null default now()
