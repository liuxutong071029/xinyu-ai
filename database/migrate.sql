create index if not exists idx_emotions_user on public.emotion_records(user_id);
comment on table public.emotion_records is '情绪记录：每日打卡/心理测评写入；AI 聊天接口顺带写入（source=AI聊天）';

-- ============================================================
-- 7. family_bindings 家庭绑定表
-- ============================================================
