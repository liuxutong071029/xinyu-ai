-- 辅助函数：当前登录用户 id（文本），便于策略书写
create or replace function public.current_uid_text() returns text
language sql stable as $$
  select (auth.uid())::text
$$;

-- ---------- users：四角色只能看/改自己的档案 ----------
drop policy if exists users_self_select on public.users;
create policy users_self_select on public.users
  for select to authenticated
  using (id::text = public.current_uid_text());

drop policy if exists users_self_update on public.users;
create policy users_self_update on public.users
  for update to authenticated
  using (id::text = public.current_uid_text());
-- 注：注册/登录为服务端 service_role 行为，不经 RLS

-- ---------- schools：学生/学校看本校，社区看本区域学校 ----------
drop policy if exists schools_visible on public.schools;
create policy schools_visible on public.schools
  for select to authenticated
  using (exists (
    select 1 from public.users u
    where u.id::text = public.current_uid_text()
      and (u.school_id = schools.id or u.region = schools.region)
  ));

-- ---------- ai_personality：学生本人可读写；家长/学校/社区无策略（默认拒绝） ----------
-- 家长可见范围限定为「心理趋势/情绪变化/AI 建议」，AI 人格配置不在开放范围
