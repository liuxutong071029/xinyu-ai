-- ============================================================
-- 行级安全 RLS · 四角色策略
-- 设计说明（重要）：
--   * 策略统一以 (auth.uid())::text 与 id/user_id::text 比较 —— 面向「接入
--     Supabase Auth 后 auth.users.id 与 users.id 对齐」的场景；
--   * 心屿 Node 服务端使用 SUPABASE_SERVICE_KEY（service_role）访问，
--     service_role 绕过 RLS，因此同等的权限边界在服务端由路由守卫逐接口实现，
--     与下列策略一一对应（见 docs/权限隔离验证记录.md）；
--   * 学校/社区端不授予任何明细表策略 → 默认拒绝（禁看学生聊天/树洞/明细）；
--     只经下方「安全定义者视图」（默认 security definer，底层 RLS 不阻断聚合）
--     读本校/本区域匿名统计。
-- ============================================================

alter table public.users            enable row level security;
alter table public.schools          enable row level security;
alter table public.ai_personality   enable row level security;
alter table public.chat_records     enable row level security;
