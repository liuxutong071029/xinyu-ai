function riskOf(text) {
  if (RISK_HIGH_WORDS.some(w => text.includes(w))) return 'high';
  if (RISK_ATTENTION_WORDS.some(w => text.includes(w))) return 'attention';
  return 'normal';
}
function detectEmotion(text) {
  let best = '平静', bestScore = 0;
  for (const emo of EMOTION_ORDER) {
    const words = EMOTION_LEXICON[emo] || [];
    let score = 0;
    for (const w of words) if (text.includes(w)) score += w.length >= 4 ? 2 : 1;
    if (score > bestScore) { bestScore = score; best = emo; }
  }
  if (bestScore === 0) return { emotion: '平静', confidence: 0 };
  return { emotion: best, confidence: Math.min(1, bestScore / 3) };
}

