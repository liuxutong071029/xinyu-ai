function extractTopics(text) {
  return MEMORY_TOPICS.filter(t => t.words.some(w => text.includes(w))).map(t => t.key);
}
function memoryAsk(history) {
  // 从最近 8 条用户消息提取主题，命中历史高频主题时返回回问
  const recent = (history || []).slice(-8).filter(m => m.role === 'user').map(m => m.content);
  if (!recent.length) return null;
  const seen = {};
  recent.forEach(t => extractTopics(t).forEach(k => { seen[k] = (seen[k] || 0) + 1; }));
  const top = Object.entries(seen).sort((a, b) => b[1] - a[1])[0];
  if (!top) return null;
  const topic = MEMORY_TOPICS.find(t => t.key === top[0]);
  if (!topic) return null;
  return topic.asks[Math.floor(Math.random() * topic.asks.length)];
}

